"""Build results/tables.md and results/spend.json from the result files (no recomputation)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}%"


out = ["# Results tables (generated by scripts/make_tables.py)\n"]
g = json.loads((R / "gate0_summary.json").read_text())
g1 = json.loads((R / "gate0_v1_prespecified" / "gate0_summary.json").read_text())
out.append("## Gate 0: reproduction of CDC P&T 2025 crude prevalence (tolerance 0.1 pp, point and both CI limits)\n")
out.append("| Cell set | Run 1 (prespecified) | Run 2 (after addendum A1) | Cells | Max abs point diff (run 2) | sample_size exact (run 2) |")
out.append("|---|---|---|---|---|---|")
for k in ("G0_primary", "G0_breakout", "G0_median"):
    a, b = g1[k], g[k]
    out.append(f"| {k} | {pct(a['rate'])} ({a['reproduced']:,}/{a['cells_compared']:,}) | {pct(b['rate'])} "
               f"({b['reproduced']:,}/{b['cells_compared']:,}) | {b['cells_compared']:,} | {b['max_abs_point_diff_pp']} pp | "
               f"{pct(b.get('sample_size_exact_rate'))} |")
for split in ("test", "test_exploratory", "stress", "stress_exploratory"):
    f = R / f"{split}_summary.json"
    if not f.exists():
        continue
    s = json.loads(f.read_text())
    out.append(f"\n## {split} (n = {s['n_items']}, provider {s.get('provider')}, commit {s['commit']}, code_dirty {s['code_dirty']}, prompt {s['prompt_version']})\n")
    out.append("| Policy | Outcome correct [95% CI] | Spec exact | Numeric agreement (answerable) | Abstain precision | Abstain recall | Cost total | Cost / q | Latency p50 / p95 | LLM calls | Cached / prompt tokens | Paths |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for p, m in s["policies"].items():
        lo, hi = m["outcome_correct_ci"]
        paths = ", ".join(f"{k}: {v}" for k, v in m["paths"].items())
        out.append(f"| {p} | {pct(m['outcome_correct'])} [{pct(lo)}, {pct(hi)}] | {pct(m['spec_exact_match'])} | "
                   f"{pct(m['numeric_agreement_answerable'])} | {pct(m['abstention_precision'])} | {pct(m['abstention_recall'])} | "
                   f"${m['cost_total_usd']:.4f} | ${m['cost_per_question_usd']:.5f} | {m['latency_median_s']:.2f} / {m['latency_p95_s']:.2f} s | "
                   f"{m['llm_calls']} | {m['cached_tokens_reported']:,} / {m['prompt_tokens']:,} | {paths} |")
    if "paired_vs_expert" in s:
        out.append("\nPaired difference vs EXPERT (Newcombe method 10, 95% CI):\n")
        out.append("| Policy | Diff (policy - EXPERT) | 95% CI | Policy-only correct | EXPERT-only correct |")
        out.append("|---|---|---|---|---|")
        for p, d in s["paired_vs_expert"].items():
            out.append(f"| {p} | {100 * d['diff']:+.1f} pp | [{100 * d['ci_low']:+.1f}, {100 * d['ci_high']:+.1f}] pp | "
                       f"{d['discordant_a_only']} | {d['discordant_b_only']} |")
ni = R / "noninferiority.json"
if ni.exists():
    out.append("\n## Prespecified non-inferiority decision\n")
    out.append("```json\n" + ni.read_text() + "\n```")

# spend: every unique API call in the cache was billed once
calls = [json.loads(l)["response"] for l in (R / "llm_cache.jsonl").read_text().splitlines() if l.strip()] \
    if (R / "llm_cache.jsonl").exists() else []
by = {}
for c in calls:
    m = by.setdefault(c["model"], {"calls": 0, "prompt_tokens": 0, "cached_tokens": 0, "completion_tokens": 0, "usd": 0.0})
    m["calls"] += 1; m["prompt_tokens"] += c["prompt_tokens"]; m["cached_tokens"] += c["cached_tokens"] or 0
    m["completion_tokens"] += c["completion_tokens"]; m["usd"] += c["cost"]
spend = {"total_usd": round(sum(m["usd"] for m in by.values()), 4), "by_model": by,
         "note": "Sum over unique cached API calls (each billed once at list price, docs/pricing.json). Rate-limited (429) attempts are not billed and not cached."}
if calls:
    (R / "spend.json").write_text(json.dumps(spend, indent=1))
    out.append(f"\n## Total LLM spend\n\n${spend['total_usd']:.2f} over {len(calls)} unique API calls: " +
               ", ".join(f"{k} {v['calls']} calls ${v['usd']:.2f}" for k, v in by.items()))
(R / "tables.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
